import { type ReactNode } from 'react';
import clsx from 'clsx';

/** The mark used wherever AI produced something, so people always know what was generated. */
export function AiMark({ className }: { className?: string }) {
  return (
    <span className={clsx('inline-flex h-5 items-center rounded-sm bg-federal-900 px-1.5 text-[10px] font-extrabold tracking-[0.04em] text-white', className)} aria-label="AI generated">
      AI
    </span>
  );
}

export function ConfidenceMeter({ value }: { value: number }) {
  const pct = Math.round(value * 100);
  const tone = pct >= 80 ? 'bg-good-600' : pct >= 60 ? 'bg-warn-600' : 'bg-crit-600';
  return (
    <span className="inline-flex items-center gap-1.5 text-xs text-graphite-600" title="Model confidence">
      <span className="h-1.5 w-14 overflow-hidden rounded-full bg-limestone-200"><span className={clsx('block h-full', tone)} style={{ width: `${pct}%` }} /></span>
      <span className="tabular-nums font-semibold">{pct}%</span>
    </span>
  );
}

/**
 * An AI result shown with its reasons and confidence. AI recommends; a person decides,
 * so every block names who approves and keeps the reasons visible.
 */
export function AiInsight({ title, confidence, reasons, children, footer, tone = 'neutral', model }: {
  title: ReactNode; confidence?: number; reasons?: string[]; children?: ReactNode; footer?: ReactNode; tone?: 'neutral' | 'good' | 'warn' | 'crit'; model?: string;
}) {
  return (
    <div className={clsx('rounded-md border p-4',
      tone === 'neutral' && 'border-federal-100 bg-federal-50/60',
      tone === 'good' && 'border-good-600/20 bg-good-50',
      tone === 'warn' && 'border-warn-600/25 bg-warn-50',
      tone === 'crit' && 'border-crit-600/20 bg-crit-50')}>
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2">
          <AiMark />
          <span className="text-sm font-bold text-graphite-900">{title}</span>
        </div>
        {confidence !== undefined && <ConfidenceMeter value={confidence} />}
      </div>
      {children && <div className="mt-2 text-sm text-graphite-800">{children}</div>}
      {reasons && reasons.length > 0 && (
        <ul className="mt-2 space-y-1">
          {reasons.map((r, i) => (
            <li key={i} className="flex gap-2 text-[13px] text-graphite-700"><span className="mt-[7px] h-1 w-1 shrink-0 rounded-full bg-graphite-500" />{r}</li>
          ))}
        </ul>
      )}
      {(footer || model) && (
        <div className="mt-3 flex flex-wrap items-center justify-between gap-2 border-t border-black/5 pt-2.5">
          <div className="flex flex-wrap gap-2">{footer}</div>
          {model && <span className="text-2xs text-graphite-500">Generated by {model}. Reviewed decisions are logged.</span>}
        </div>
      )}
    </div>
  );
}
