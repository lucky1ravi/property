// Checks that every requirement in requirements/requirements.json is covered by at least one test whose title contains [ID],
// that no test points at an unknown requirement, and writes requirements/TRACEABILITY.md.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const reqs = JSON.parse(readFileSync(join(root, 'requirements/requirements.json'), 'utf8'));
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : p.endsWith('.spec.ts') && files.push(p); } })(join(root, 'tests'));

const found = new Map(); // id -> [{file, count}]
let totalTests = 0;
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  totalTests += (src.match(/\btest(\.\w+)?\(\s*[`'"]/g) || []).length;
  for (const m of src.matchAll(/\btest(?:\.\w+)?\(\s*[`'"]([^`'"]*)/g)) {
    for (const id of m[1].matchAll(/\[([A-Z]+-\d\d)\]/g)) {
      const k = id[1]; const list = found.get(k) || []; const rel = relative(root, f);
      const e = list.find((x) => x.file === rel); e ? e.count++ : list.push({ file: rel, count: 1 }); found.set(k, list);
    }
  }
}
const known = new Set(reqs.map((r) => r.id));
const missing = reqs.filter((r) => !found.has(r.id));
const unknown = [...found.keys()].filter((k) => !known.has(k));

let md = `# Requirement traceability\n\nGenerated by \`npm run trace\`. Every requirement is covered by at least one test whose title starts with its ID.\n\n` +
  `* Requirements: **${reqs.length}**, covered: **${reqs.length - missing.length}**\n* Test cases (static count): **${totalTests}** in **${files.length}** spec files\n\n` +
  `| ID | Area | Requirement | Tests (file x count) |\n| --- | --- | --- | --- |\n`;
for (const r of reqs) md += `| ${r.id} | ${r.area} | ${r.text} | ${(found.get(r.id) || []).map((x) => `${x.file.replace('tests/', '')} x${x.count}`).join('<br>') || '**NOT COVERED**'} |\n`;
writeFileSync(join(root, 'requirements/TRACEABILITY.md'), md);
console.log(`requirements ${reqs.length}, covered ${reqs.length - missing.length}, tests ${totalTests}, spec files ${files.length}`);
if (missing.length) console.log('NOT COVERED:', missing.map((r) => r.id).join(', '));
if (unknown.length) console.log('UNKNOWN IDs in tests:', unknown.join(', '));
process.exit(missing.length || unknown.length ? 1 : 0);
